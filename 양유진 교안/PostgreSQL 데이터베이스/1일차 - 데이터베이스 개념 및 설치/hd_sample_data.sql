-- 기존 샘플 테이블 초기화: 자식 테이블 -> 부모 테이블 순서
DROP TABLE IF EXISTS salary_history;
DROP TABLE IF EXISTS employee_projects;
DROP TABLE IF EXISTS projects;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS jobs;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS locations;

-- 1) 지역: 부서 위치 정보
CREATE TABLE locations (
    location_id    INTEGER PRIMARY KEY,
    city           VARCHAR(40) NOT NULL,
    region         VARCHAR(40) NOT NULL,
    country_code   CHAR(2) NOT NULL DEFAULT 'KR'
);

-- 2) 부서: 빈 부서를 포함하여 LEFT JOIN 실습 가능
CREATE TABLE departments (
    department_id   INTEGER PRIMARY KEY,
    department_name VARCHAR(50) NOT NULL UNIQUE,
    location_id     INTEGER REFERENCES locations(location_id),
    annual_budget   BIGINT NOT NULL CHECK (annual_budget >= 0)
);

-- 3) 직무: 직원에게 직무를 연결하고 급여 범위를 조회할 수 있음
CREATE TABLE jobs (
    job_id       VARCHAR(20) PRIMARY KEY,
    job_title    VARCHAR(60) NOT NULL,
    min_salary   INTEGER NOT NULL CHECK (min_salary >= 0),
    max_salary   INTEGER NOT NULL,
    CONSTRAINT chk_job_salary_range CHECK (max_salary >= min_salary)
);

-- 4) 직원: manager_id가 자기 자신의 employee_id를 참조 (SELF JOIN)
-- department_id가 NULL인 직원, phone_number가 NULL인 직원이 포함됨
CREATE TABLE employees (
    employee_id       INTEGER PRIMARY KEY,
    first_name        VARCHAR(30) NOT NULL,
    last_name         VARCHAR(20) NOT NULL,
    email             VARCHAR(100) NOT NULL UNIQUE,
    phone_number      VARCHAR(20),
    hire_date         DATE NOT NULL,
    job_id            VARCHAR(20) NOT NULL REFERENCES jobs(job_id),
    salary            INTEGER NOT NULL CHECK (salary >= 0),
    manager_id        INTEGER REFERENCES employees(employee_id),
    department_id     INTEGER REFERENCES departments(department_id),
    employment_status VARCHAR(10) NOT NULL DEFAULT '재직'
        CHECK (employment_status IN ('재직', '휴직', '퇴사')),
    commission_pct    NUMERIC(4,2)
        CHECK (commission_pct BETWEEN 0 AND 1)
);

-- 5) 프로젝트: 부서마다 여러 프로젝트를 관리할 수 있음
CREATE TABLE projects (
    project_id      INTEGER PRIMARY KEY,
    project_name    VARCHAR(100) NOT NULL,
    department_id   INTEGER REFERENCES departments(department_id),
    start_date      DATE NOT NULL,
    end_date        DATE,
    budget          BIGINT NOT NULL CHECK (budget >= 0),
    project_status  VARCHAR(10) NOT NULL
        CHECK (project_status IN ('계획','진행','완료','보류')),
    CONSTRAINT chk_project_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

-- 6) 프로젝트 참여: 직원(N)과 프로젝트(N)를 연결하는 다대다 관계
-- 복합키(employee_id, project_id) 실습에 활용
CREATE TABLE employee_projects (
    employee_id     INTEGER NOT NULL REFERENCES employees(employee_id),
    project_id      INTEGER NOT NULL REFERENCES projects(project_id),
    project_role    VARCHAR(20) NOT NULL,
    assigned_date   DATE NOT NULL,
    allocation_pct  INTEGER NOT NULL CHECK (allocation_pct BETWEEN 1 AND 100),
    PRIMARY KEY (employee_id, project_id)
);

-- 7) 급여 변경 이력: 한 직원에 여러 변경 이력이 연결됨
CREATE TABLE salary_history (
    history_id      INTEGER PRIMARY KEY,
    employee_id     INTEGER NOT NULL REFERENCES employees(employee_id),
    change_date     DATE NOT NULL,
    old_salary      INTEGER NOT NULL CHECK (old_salary >= 0),
    new_salary      INTEGER NOT NULL CHECK (new_salary >= 0),
    change_reason   VARCHAR(50) NOT NULL,
    CONSTRAINT uq_employee_salary_change UNIQUE (employee_id, change_date)
);


