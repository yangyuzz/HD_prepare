-- [기초] 직원 정보 10건 확인
SELECT employee_id, last_name || first_name AS employee_name,
       job_id, salary, department_id
FROM employees
ORDER BY employee_id
LIMIT 10;

-- [JOIN] 부서별 직원 수: 직원 0명인 신사업기획팀도 결과에 포함됨
SELECT d.department_name, COUNT(e.employee_id) AS employee_count
FROM departments AS d
LEFT JOIN employees AS e ON d.department_id = e.department_id
GROUP BY d.department_id, d.department_name
ORDER BY d.department_id;

-- [SELF JOIN] 직원-상사 관계 확인
SELECT e.employee_id, e.last_name || e.first_name AS employee_name,
       m.last_name || m.first_name AS manager_name
FROM employees AS e
LEFT JOIN employees AS m ON e.manager_id = m.employee_id
ORDER BY e.employee_id
LIMIT 15;
