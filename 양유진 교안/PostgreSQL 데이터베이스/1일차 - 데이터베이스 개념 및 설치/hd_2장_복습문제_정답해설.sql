-- -----------------------------------------------------------------------------
-- [복습 10] WHERE의 중요성
-- -----------------------------------------------------------------------------
-- 문제: UPDATE employees SET salary = salary + 100000; 의 위험은 무엇인가? 특정 employee_id=123만 수정하도록 고치시오.

-- [모범답안]
-- WHERE가 없으면 모든 직원의 급여가 변경될 수 있다.
-- 실습 안전장치: 변경 전 트랜잭션을 시작하고, 확인 후 반드시 되돌린다.
BEGIN;
UPDATE employees
SET salary = salary + 100000
WHERE employee_id = 123;
SELECT employee_id, salary FROM employees WHERE employee_id = 123;
ROLLBACK;

-- 해설: 예시 답안은 직접 실행하지 말고 BEGIN/ROLLBACK으로 보호한다.

-- -----------------------------------------------------------------------------
-- [복습 11] 트랜잭션과 ACID
-- -----------------------------------------------------------------------------
-- 문제: BEGIN, COMMIT, ROLLBACK의 역할을 설명하고 ACID 중 원자성의 의미를 쓰시오.

-- [모범답안]
-- BEGIN은 트랜잭션 시작, COMMIT은 변경 확정, ROLLBACK은 미확정 변경 취소이다. 원자성은 작업을 모두 성공시키거나 모두 취소하는 성질이다.

-- 해설: TCL을 사용하면 실습 과정의 변경을 복원할 수 있다.

