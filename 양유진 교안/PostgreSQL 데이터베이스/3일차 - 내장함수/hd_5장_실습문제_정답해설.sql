-- ------------------------------------------------------------------------------------
-- [실습 25] employees의 입사월·입사 연도·근무일수 | 교안 p.22, 24~28
-- ------------------------------------------------------------------------------------
-- 문제: 직원의 입사월, 입사 연도 및 현재까지 경과 일수를 조회하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT employee_id, hire_date,
       DATE_TRUNC('month', hire_date)::DATE AS 입사월초,
