-- [실습 01] 대소문자 변환: UPPER·LOWER·INITCAP | 교안 p.4, 6
-- ------------------------------------------------------------------------------------
-- 문제: 세 함수로 같은 문자열의 표기 차이를 확인하고, 직원 email을 대문자로 변환해 보시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT UPPER('hello world') AS 대문자,
       LOWER('HELLO WORLD') AS 소문자,
       INITCAP('hello world') AS 첫글자대문자;
SELECT employee_id, email, UPPER(email) AS 대문자이메일
FROM employees ORDER BY employee_id LIMIT 5;
-- 해설: UPPER=대문자, LOWER=소문자, INITCAP=영문 단어 첫 글자 대문자. 한글 이름 자체는 대소문자 변화가 없다.

-- ------------------------------------------------------------------------------------
-- [실습 02] 문자열 길이와 공백 제거 | 교안 p.4, 7~8
-- ------------------------------------------------------------------------------------
-- 문제: 길이 10인 문자열에서 TRIM·LTRIM·RTRIM 결과와 제거 후 길이를 비교하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT LENGTH('  M14860  ') AS 공백포함길이,
       TRIM('  M14860  ') AS 양쪽제거,
       LTRIM('  M14860  ') AS 왼쪽제거,
       RTRIM('  M14860  ') AS 오른쪽제거,
       LENGTH(TRIM('  M14860  ')) AS 양쪽제거후길이;
-- 해설: 앞뒤에 공백 두 개씩 있어 길이는 10. TRIM은 양쪽, LTRIM은 왼쪽, RTRIM은 오른쪽만 제거.

