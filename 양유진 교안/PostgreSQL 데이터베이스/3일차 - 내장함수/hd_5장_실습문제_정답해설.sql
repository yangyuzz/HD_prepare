-- ------------------------------------------------------------------------------------
-- [실습 31] 핵심 직접 완성: NULLIF로 0 나누기 방지 | 교안 p.33~34, 43
-- ------------------------------------------------------------------------------------
-- 문제: 10/0을 직접 실행하지 말고, 분모가 0일 때 NULL로 바꾸도록 빈칸을 완성하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT 10 / NULLIF(0, 0) AS 안전한_0나눗셈,
       10 / NULLIF(2, 0) AS 정상나눗셈,
       COALESCE(10 / NULLIF(0, 0), -1) AS NULL대체;
-- 해설: NULLIF(0,0)은 NULL → 10/NULL은 오류가 아니라 NULL. 다른 값이면 분모 그대로. PostgreSQL
-- 해설: 정수 나눗셈 10/2=5.

-- ------------------------------------------------------------------------------------
-- [실습 32] COALESCE와 NULLIF를 함께 사용하기 | 교안 p.33~34, 43
-- ------------------------------------------------------------------------------------
-- 문제: 재직 상태를 NULLIF로 빈 값처럼 만든 후 COALESCE로 안내 문구를 표시하시오.
