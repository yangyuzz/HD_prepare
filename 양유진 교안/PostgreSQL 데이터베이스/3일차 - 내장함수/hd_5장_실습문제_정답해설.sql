       AGE(CURRENT_DATE, hire_date) AS 근무기간
FROM employees ORDER BY employee_id LIMIT 8;
-- 해설: DATE_TRUNC의 TIMESTAMP 결과에서 ::DATE로 날짜만 남길 수 있다. 결과는 실행 날짜에 따라 달라진다.

