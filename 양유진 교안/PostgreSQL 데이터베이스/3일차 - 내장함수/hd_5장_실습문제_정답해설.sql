-- ------------------------------------------------------------------------------------
-- [실습 06] 문자열 연결: CONCAT·||·CONCAT_WS | 교안 p.5, 10
-- ------------------------------------------------------------------------------------
-- 문제: 문자열 연결 세 방식의 결과를 비교하고, employees의 성·이름을 결합하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT CONCAT('설비-', 'M14860') AS 함수연결,
       '설비-' || 'M14860' AS 연산자연결,
       CONCAT_WS('-', '설비', 'M14860', 'H') AS 구분자연결;
SELECT employee_id, CONCAT(last_name, first_name) AS 직원명,
       CONCAT_WS(' / ', last_name || first_name, job_id) AS 직원과직무
FROM employees ORDER BY employee_id LIMIT 5;
-- 해설: CONCAT_WS의 첫 번째 인수는 구분자. ||는 연결 연산자이다.

-- ------------------------------------------------------------------------------------
-- [실습 07] CONCAT과 ||가 NULL을 만났을 때 | 교안 p.11, 42
-- ------------------------------------------------------------------------------------
-- 문제: 세 표현식의 결과가 각각 AB, NULL, AB인지 확인하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT CONCAT('A', NULL, 'B') AS CONCAT결과,
       'A' || NULL || 'B' AS 파이프결과,
       'A' || COALESCE(NULL, '') || 'B' AS 안전한연결;
-- 해설: PostgreSQL CONCAT은 NULL 인수를 건너뛰지만 ||의 피연산자가 NULL이면 연결 결과가 NULL이다.

-- ------------------------------------------------------------------------------------
-- [실습 08] 직원 연락처 문자열 만들기 | 교안 p.10~11
-- ------------------------------------------------------------------------------------
-- 문제: 전화번호가 없는 직원도 표시할 수 있도록 이름과 연락처를 연결해 출력하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT employee_id,
       CONCAT(last_name, first_name) AS 직원명,
       '연락처: ' || COALESCE(phone_number, '미등록') AS 연락처표시
FROM employees ORDER BY employee_id LIMIT 12;
-- 해설: 문자열 연결에 NULL이 끼면 || 결과가 NULL이므로 COALESCE로 사전에 대체한다.

