-- ------------------------------------------------------------------------------------
-- [실습 30] NULLIF의 기본 동작: 같으면 NULL | 교안 p.33~34, 43
-- ------------------------------------------------------------------------------------
-- 문제: NULLIF(a,b)의 비교 결과와 직원의 재직 상태 변환을 확인하시오.
-- [정답 SQL] 아래 쿼리 실행
SELECT NULLIF(10, 10) AS 같으면NULL,
