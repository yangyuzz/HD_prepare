-- ------------------------------------------------------------------------------------
-- [과제 06] 입사월별 인원 집계 | 교안 p.24~26
-- ------------------------------------------------------------------------------------
-- 문제: employees의 입사 월(해당 월 1일) 기준으로 입사자 수를 집계하시오. 연월 오름차순으로 정렬하고 DATE_TRUNC 결과는
-- 문제: ::DATE로 바꾸시오.
-- [모범 SQL]
SELECT DATE_TRUNC('month',hire_date)::DATE AS 입사월,
       COUNT(*) AS 입사인원
FROM employees
GROUP BY DATE_TRUNC('month',hire_date)::DATE
ORDER BY 입사월;
-- 해설: DATE_TRUNC의 월초 기준으로 그룹화해야 다른 연도의 3월을 합치지 않는다.

-- ------------------------------------------------------------------------------------
-- [과제 07] 연도별·분기별 입사자 수 | 교안 p.25~26
-- ------------------------------------------------------------------------------------
-- 문제: EXTRACT를 사용해 입사연도와 분기별 입사자 수를 집계하고 연도와 분기 오름차순으로 정렬하시오.
-- [모범 SQL]
SELECT EXTRACT(YEAR FROM hire_date) AS 입사연도,
       EXTRACT(QUARTER FROM hire_date) AS 입사분기,
       COUNT(*) AS 입사인원
FROM employees
GROUP BY EXTRACT(YEAR FROM hire_date), EXTRACT(QUARTER FROM hire_date)
ORDER BY 입사연도, 입사분기;
-- 해설: EXTRACT의 YEAR, QUARTER를 함께 그룹화해야 연도별 분기를 분리한다.

