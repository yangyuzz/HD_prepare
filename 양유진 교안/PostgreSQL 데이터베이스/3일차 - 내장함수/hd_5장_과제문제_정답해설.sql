-- ------------------------------------------------------------------------------------
-- [과제 10] NULLIF와 COALESCE를 결합한 상태 표시 | 교안 p.33~34
-- ------------------------------------------------------------------------------------
-- 문제: 사번·상태·상태표시를 조회하시오. 상태가 재직이면 NULLIF로 NULL로 만든 후 COALESCE로 정상 재직이라고 표시하고,
-- 문제: 휴직/퇴사는 원래 상태를 유지하시오.
-- [모범 SQL]
SELECT employee_id, employment_status,
       COALESCE(NULLIF(employment_status, '재직'), '정상 재직') AS 상태표시
FROM employees ORDER BY employee_id;
-- 해설: NULLIF(재직, 재직)=NULL → COALESCE가 정상 재직으로 대체.

