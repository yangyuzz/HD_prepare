-- ------------------------------------------------------------------------------------
-- [과제 09] 급여 구간과 재직 상태 동시 분류 | 교안 p.29~32
-- ------------------------------------------------------------------------------------
-- 문제: employee_id 120~128번에 대해 salary가 300만 미만이면 초급, 500만 미만이면 일반, 700만 미만이면
-- 문제: 고급, 나머지는 관리급으로 표시하시오. 상태는 재직/휴직/퇴사를 단순 CASE로 분류하여 한글 안내 문구로 보이시오.
-- [모범 SQL]
SELECT employee_id, salary, employment_status,
       CASE
           WHEN salary < 3000000 THEN '초급'
           WHEN salary < 5000000 THEN '일반'
           WHEN salary < 7000000 THEN '고급'
           ELSE '관리급'
       END AS 급여구간,
       CASE employment_status
           WHEN '재직' THEN '정상 근무'
           WHEN '휴직' THEN '휴직 중'
           WHEN '퇴사' THEN '퇴사자'
           ELSE '확인 필요'
       END AS 상태설명
FROM employees
WHERE employee_id BETWEEN 120 AND 128
ORDER BY employee_id;
-- 해설: 검색 CASE와 단순 CASE를 동시에 활용. WHEN은 순서대로 검사한다.

