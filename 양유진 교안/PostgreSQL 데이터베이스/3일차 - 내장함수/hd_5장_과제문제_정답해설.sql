-- [과제 03] 급여 단위 변환·보고서 숫자 표기 | 교안 p.12~15, 39~40
-- ------------------------------------------------------------------------------------
-- 문제: 사번·급여·만원 단위 급여·천 단위 쉼표가 있는 급여 텍스트를 출력하시오. employee_id 100~105만 조회하시오.
-- [모범 SQL]
SELECT employee_id, salary,
