-- [과제 02] 이름과 연락처를 NULL 안전하게 연결 | 교안 p.10~11, 33
-- ------------------------------------------------------------------------------------
-- 문제: 직원 사번과 성명, `이름 / 연락처` 문자열을 만드시오. 연락처 NULL은 미등록으로 표시하고 사번 오름차순 12명 출력하시오.
-- [모범 SQL]
SELECT employee_id,
       CONCAT(last_name, first_name) AS 성명,
       CONCAT(last_name, first_name) || ' / ' || COALESCE(phone_number, '미등록') AS 표시문자열
FROM employees ORDER BY employee_id LIMIT 12;
-- 해설: || 연산 전 COALESCE로 NULL 처리.

