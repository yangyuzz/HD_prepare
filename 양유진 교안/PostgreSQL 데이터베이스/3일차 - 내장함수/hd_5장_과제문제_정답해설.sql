-- ------------------------------------------------------------------------------------
-- [과제 08] 근무기간과 입사 1주년 날짜 | 교안 p.22, 27~28
-- ------------------------------------------------------------------------------------
-- 문제: 사번 100~108번의 입사일, 입사 1년 후 시점, 오늘 기준 근무 일수와 근무기간(AGE)을 조회하시오.
-- [모범 SQL]
SELECT employee_id, hire_date,
       (hire_date + INTERVAL '1 year')::DATE AS 입사일주년,
       CURRENT_DATE - hire_date AS 근무일수,
       AGE(CURRENT_DATE, hire_date) AS 근무기간
FROM employees
WHERE employee_id BETWEEN 100 AND 108
ORDER BY employee_id;
-- 해설: DATE+INTERVAL은 TIMESTAMP이므로 날짜만 필요하면 ::DATE. AGE는 연·월·일 간격.

