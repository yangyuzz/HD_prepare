-- ------------------------------------------------------------------------------------
-- [과제 13] 문자 날짜 처리와 날짜 범위 비교 | 교안 p.12, 41
-- ------------------------------------------------------------------------------------
-- 문제: 15/03/2025 형식의 문자열을 DATE로 만들고, employees에서 2025-01-01부터 2025-12-31까지 입사한
-- 문제: 직원의 사번·입사일을 조회하시오.
-- [모범 SQL]
SELECT TO_DATE('15/03/2025', 'DD/MM/YYYY') AS 텍스트변환,
       '2025-03-15'::DATE AS 표준형변환;
SELECT employee_id, hire_date
FROM employees
WHERE hire_date >= DATE '2025-01-01'
  AND hire_date < DATE '2026-01-01'
ORDER BY hire_date, employee_id;
-- 해설: TO_DATE는 형식을 명시하는 문자 → DATE. 날짜 범위는 다음 연도 1월 1일 미만으로 표현 가능.
