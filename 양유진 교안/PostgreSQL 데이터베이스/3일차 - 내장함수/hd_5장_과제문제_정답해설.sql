-- ------------------------------------------------------------------------------------
-- [과제 11] NULLIF 안전 나눗셈과 NUMERIC | 교안 p.14~15, 33~34
-- ------------------------------------------------------------------------------------
-- 문제: 직원 수를 0으로 나누지 않도록, 재직자 수를 전체 직원 수로 나눈 비율을 소수 4자리로 계산하시오. COUNT(*)와 CASE,
-- 문제: NULLIF를 활용하시오.
-- [모범 SQL]
SELECT COUNT(*) AS 전체직원,
       SUM(CASE WHEN employment_status = '재직' THEN 1 ELSE 0 END) AS 재직직원,
       ROUND(SUM(CASE WHEN employment_status = '재직' THEN 1 ELSE 0 END)::NUMERIC
             / NULLIF(COUNT(*), 0), 4) AS 재직비율
FROM employees;
-- 해설: 집계 전체가 0일 때 NULLIF(COUNT(*),0)으로 0 나누기를 방지한다. ::NUMERIC은 소수 계산 목적.

