-- ------------------------------------------------------------------------------------
-- [과제 04] 급여 금액 반올림과 기준값 비교 | 교안 p.17~20
-- ------------------------------------------------------------------------------------
-- 문제: 직원별 급여를 만원 단위로 바꾼 뒤 소수 첫째 자리에서 반올림하시오. 급여가 500만 미만이면 500만을 표시하는 기준급여도
-- 문제: 구하시오. 사번 123~130번 조회.
-- [모범 SQL]
SELECT employee_id, salary,
       ROUND(salary::NUMERIC / 10000, 1) AS 급여만원_소수1자리,
       GREATEST(salary, 5000000) AS 기준급여
FROM employees WHERE employee_id BETWEEN 123 AND 130
ORDER BY employee_id;
-- 해설: ROUND(값,1)은 NUMERIC 오버로드가 필요. GREATEST는 같은 행에서 최대값 선택.

-- ------------------------------------------------------------------------------------
-- [과제 05] 여러 행 최대 급여와 행 내 비교 차이 | 교안 p.20
-- ------------------------------------------------------------------------------------
-- 문제: 직원 전체의 최저·최고 급여를 집계하고, 직원별 급여와 600만원 중 작은 값은 별도로 구하시오. 두 개의 SELECT를
-- 문제: 작성하시오.
-- [모범 SQL]
SELECT MIN(salary) AS 최저급여, MAX(salary) AS 최고급여
FROM employees;
SELECT employee_id, salary, LEAST(salary,6000000) AS 제한급여
FROM employees ORDER BY employee_id LIMIT 10;
-- 해설: MIN/MAX는 행 전체 집계. LEAST는 각 행에서 비교.

