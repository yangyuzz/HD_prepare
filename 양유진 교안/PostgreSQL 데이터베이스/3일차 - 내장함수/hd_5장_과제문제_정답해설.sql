-- 문제: employees의 사번·전체이름·소문자 이메일·이메일 앞 11글자를 표시하시오. 전체이름에는 CONCAT, 이메일에는 LOWER,
-- 문제: LEFT를 사용하고 사번 순 상위 10명을 출력하시오.
-- [모범 SQL]
SELECT employee_id,
       CONCAT(last_name, first_name) AS 전체이름,
