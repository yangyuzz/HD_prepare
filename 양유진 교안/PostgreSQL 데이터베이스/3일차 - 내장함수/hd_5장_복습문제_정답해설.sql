-- [복습 11] COALESCE와 NULLIF | 교안 p.33~34
-- ------------------------------------------------------------------------------------
-- 문제: COALESCE(NULL,'미등록'), NULLIF(10,10), NULLIF(10,20), 10/NULLIF(0,0)의 결과와
