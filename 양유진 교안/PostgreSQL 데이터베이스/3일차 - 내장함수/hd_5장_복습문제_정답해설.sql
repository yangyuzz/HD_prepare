-- ------------------------------------------------------------------------------------
-- [복습 12] TO_CHAR·DATE_TRUNC·TO_DATE | 교안 p.35~41
-- ------------------------------------------------------------------------------------
-- 문제: 날짜 계산/월별 묶기, 읽기 쉬운 날짜 텍스트, 15/03/2025 문자열을 DATE로 만들기에 각각 무엇을 쓸지 답하시오.
-- [모범 SQL]
SELECT DATE_TRUNC('month', DATE '2025-03-15') AS 계산기준,
       TO_CHAR(DATE '2025-03-15','YYYY년 MM월 DD일') AS 출력문자,
       TO_DATE('15/03/2025','DD/MM/YYYY') AS 읽어온날짜;
-- 해설: DATE_TRUNC는 날짜/시각, TO_CHAR는 TEXT, TO_DATE는 DATE. 표준 날짜는 ::DATE도 가능.

