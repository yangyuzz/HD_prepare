-- ------------------------------------------------------------------------------------
-- [복습 02] CONCAT과 ||의 NULL 차이 | 교안 p.10~11
-- ------------------------------------------------------------------------------------
-- 문제: CONCAT('A', NULL, 'B')와 'A'||NULL||'B'의 결과를 비교하고, 두 번째 표현식을 안전하게 바꾸시오.
-- [모범 SQL]
SELECT CONCAT('A', NULL, 'B') AS 함수결과,
       'A' || NULL || 'B' AS 연산자결과,
       'A' || COALESCE(NULL, '') || 'B' AS 안전연결;
-- 해설: CONCAT은 NULL을 무시해 AB, ||는 NULL을 전파, COALESCE로 빈 문자를 넣으면 AB.

