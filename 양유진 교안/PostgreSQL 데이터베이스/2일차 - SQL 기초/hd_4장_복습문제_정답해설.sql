-- [복습문제 02] SQL 작성과 처리 순서
-- ------------------------------------------------------------------------------
-- 문제: SELECT·FROM·WHERE·GROUP BY·HAVING·ORDER BY·LIMIT의 작성 순서와 처리 순서를 각각 정리하고 DISTINCT의 처리 위치를 설명하시오.
-- 학습 요소: SQL 논리적 처리

-- [모범답안]
-- 작성: SELECT → FROM → WHERE → GROUP BY → HAVING → ORDER BY → LIMIT
-- 처리: FROM → WHERE → GROUP BY → HAVING → SELECT → [DISTINCT] → ORDER BY → LIMIT
-- DISTINCT는 SELECT 결과의 중복을 ORDER BY 전에 제거한다.

-- 해설: 작성 순서와 결과를 이해하는 논리적 처리 순서는 다르다.

-- ------------------------------------------------------------------------------
-- [복습문제 03] WHERE와 HAVING
-- ------------------------------------------------------------------------------
-- 문제: 급여 500만 원 이상의 개별 직원만 남길 때와 직원이 5명 이상인 부서 그룹만 남길 때 사용할 절을 구분하시오.
-- 학습 요소: WHERE · HAVING

-- [모범답안]
-- WHERE salary >= 5000000 : 그룹화 전 개별 직원 행 필터링
-- HAVING COUNT(*) >= 5 : 그룹화 후 부서 그룹 필터링

-- 해설: WHERE는 GROUP BY 전에, HAVING은 GROUP BY 후에 논리적으로 평가된다.


