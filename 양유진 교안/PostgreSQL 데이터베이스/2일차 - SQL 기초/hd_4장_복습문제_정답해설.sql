-- ------------------------------------------------------------------------------
-- [복습문제 12] LIMIT·OFFSET 페이징
-- ------------------------------------------------------------------------------
-- 문제: 페이지당 10건일 때 3페이지의 LIMIT/OFFSET을 구하고, 결과를 안정적으로 페이지에 나누기 위해 필요한 절을 설명하시오. SQL 한 문장을 작성하시오.
-- 학습 요소: LIMIT · OFFSET

-- [모범답안]
-- LIMIT 10 OFFSET 20;
-- 유일한 열(employee_id)까지 포함한 ORDER BY가 필요하다.
SELECT employee_id, first_name
FROM employees
ORDER BY employee_id
LIMIT 10 OFFSET 20;

-- 해설: OFFSET = (페이지번호 - 1) × 페이지당 개수.

