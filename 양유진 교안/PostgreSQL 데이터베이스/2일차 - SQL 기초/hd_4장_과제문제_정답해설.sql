-- ------------------------------------------------------------------------------
-- [과제문제 07] NULL인 연락처를 표시용 값으로 변환
-- ------------------------------------------------------------------------------
-- 문제: 전화번호가 없는 직원만 찾아 사번·이름과 '미등록'으로 대체한 연락처를 표시하시오. 사번 오름차순으로 조회하시오.
-- 학습 요소: IS NULL · COALESCE

-- [모범답안]
SELECT employee_id, first_name,
       COALESCE(phone_number, '미등록') AS 연락처
FROM employees
WHERE phone_number IS NULL
ORDER BY employee_id;

-- 해설: IS NULL로 미등록 직원을 찾고 COALESCE로 보기 쉬운 문자열을 출력한다.

-- ------------------------------------------------------------------------------
-- [과제문제 08] NOT IN과 NULL을 함께 처리
-- ------------------------------------------------------------------------------
-- 문제: 40·50번 부서가 아닌 직원 및 부서 미배정 직원을 모두 조회하시오. 직원 사번·이름·부서 ID를 사번순으로 출력하고 NULL을 의도적으로 포함하도록 조건을 작성하시오.
-- 학습 요소: NOT IN · IS NULL

-- [모범답안]
SELECT employee_id, first_name, department_id
FROM employees
WHERE department_id NOT IN (40, 50)
   OR department_id IS NULL
ORDER BY employee_id;

-- 해설: NOT IN 자체는 department_id가 NULL인 행을 제외하므로 OR ... IS NULL을 추가한다.


