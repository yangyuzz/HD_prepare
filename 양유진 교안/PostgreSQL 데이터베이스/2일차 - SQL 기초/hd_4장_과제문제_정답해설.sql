-- ------------------------------------------------------------------------------
-- [과제문제 01] 조건별 직원 조회 보고서
-- ------------------------------------------------------------------------------
-- 문제: 재직 중인 직원 중 급여 600만 원 이상인 직원의 사번·이름·급여를 각각 사번·이름·급여라는 별칭으로 출력하시오. 급여 내림차순, 동점 사번 오름차순, 상위 10명만 표시하시오.
-- 학습 요소: SELECT · WHERE · AS · ORDER BY · LIMIT

-- [모범답안]
SELECT employee_id AS 사번, first_name AS 이름, salary AS 급여
FROM employees
WHERE employment_status = '재직'
  AND salary >= 6000000
ORDER BY 급여 DESC, 사번 ASC
LIMIT 10;

-- 해설: SELECT 별칭, WHERE, ORDER BY, LIMIT을 한 번에 사용한다. 같은 SELECT 별칭은 ORDER BY에서 사용할 수 있다.

-- ------------------------------------------------------------------------------
-- [과제문제 02] 재직 직원 부서별 집계
-- ------------------------------------------------------------------------------
-- 문제: 부서가 배정된 재직 직원만 대상으로 부서별 인원을 세시오. 재직자 5명 이상인 부서만 남기고 인원 내림차순, 부서 ID 오름차순으로 조회하시오.
-- 학습 요소: GROUP BY · HAVING

-- [모범답안]
SELECT department_id, COUNT(*) AS active_count
FROM employees
WHERE employment_status = '재직'
  AND department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 5
ORDER BY active_count DESC, department_id ASC;

-- 해설: WHERE는 행, GROUP BY는 묶음, HAVING은 묶음 필터링에 사용한다.


