-- ------------------------------------------------------------------------------
-- [과제문제 03] 논리 연산자와 괄호
-- ------------------------------------------------------------------------------
-- 문제: 재직 중이며 부서가 40 또는 50에 속한 직원의 사번·부서·상태를 사번 순으로 조회하시오. AND와 OR, 괄호를 반드시 사용하시오.
-- 학습 요소: AND · OR · 괄호

-- [모범답안]
SELECT employee_id, department_id, employment_status
FROM employees
WHERE employment_status = '재직'
  AND (department_id = 40 OR department_id = 50)
ORDER BY employee_id;

-- 해설: 괄호가 없으면 50번 부서의 휴직자까지 포함할 수 있다.

-- ------------------------------------------------------------------------------
-- [과제문제 04] IN + BETWEEN 동시 사용
-- ------------------------------------------------------------------------------
-- 문제: 부서가 40·50·60 중 하나이며 급여가 450만~650만 원(경계 포함)인 직원의 사번·부서·급여를 부서 오름차순, 급여 내림차순으로 조회하시오.
-- 학습 요소: IN · BETWEEN

-- [모범답안]
SELECT employee_id, department_id, salary
FROM employees
WHERE department_id IN (40, 50, 60)
  AND salary BETWEEN 4500000 AND 6500000
ORDER BY department_id, salary DESC, employee_id;

-- 해설: IN과 BETWEEN을 AND로 결합하며 두 조건을 모두 만족하는 행만 남긴다.

-- ------------------------------------------------------------------------------
-- [과제문제 05] 문자 패턴 복합 검색
-- ------------------------------------------------------------------------------
-- 문제: 이름이 '지'로 시작하거나 이메일에 'EMPLOYEE15'가 포함되는 직원을 조회하시오. 이메일 검색은 대소문자를 무시하고, 사번·이름·이메일을 사번 순으로 표시하시오.
-- 학습 요소: LIKE · ILIKE · OR

-- [모범답안]
SELECT employee_id, first_name, email
FROM employees
WHERE first_name LIKE '지%'
   OR email ILIKE '%EMPLOYEE15%'
ORDER BY employee_id;

-- 해설: LIKE와 ILIKE, OR를 함께 사용한다. 한글 이름 패턴은 LIKE로, 대소문자 무시 이메일은 ILIKE로 검사한다.

-- ------------------------------------------------------------------------------
-- [과제문제 06] 2024년 입사자 검색
-- ------------------------------------------------------------------------------
-- 문제: 2024년 1월 1일부터 12월 31일까지 입사한 직원의 사번·이름·입사일을 입사일 오름차순, 사번 오름차순으로 조회하시오.
-- 학습 요소: BETWEEN · DATE

-- [모범답안]
SELECT employee_id, first_name, hire_date
FROM employees
WHERE hire_date BETWEEN DATE '2024-01-01' AND DATE '2024-12-31'
ORDER BY hire_date, employee_id;

-- 해설: hire_date가 DATE형이므로 BETWEEN으로 날짜 경계를 모두 포함한다.


