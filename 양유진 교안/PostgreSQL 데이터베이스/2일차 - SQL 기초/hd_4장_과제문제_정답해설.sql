-- ------------------------------------------------------------------------------
-- [과제문제 09] DISTINCT 조합 추출
-- ------------------------------------------------------------------------------
-- 문제: 재직자에게 존재하는 부서 ID와 직무 코드의 조합을 중복 없이 표시하시오. NULL 부서는 제외하고 부서·직무 오름차순으로 조회하시오.
-- 학습 요소: DISTINCT · WHERE · ORDER BY

-- [모범답안]
SELECT DISTINCT department_id, job_id
FROM employees
WHERE employment_status = '재직'
  AND department_id IS NOT NULL
ORDER BY department_id, job_id;

-- 해설: DISTINCT는 선택한 두 열의 조합을 기준으로 중복을 제거한다.

-- ------------------------------------------------------------------------------
-- [과제문제 10] 수수료율 정렬과 상위 N건
-- ------------------------------------------------------------------------------
-- 문제: 직원별 수수료율을 높은 순서로 정렬하여 상위 10명의 사번·이름·수수료율을 조회하시오. NULL은 가장 뒤에 두고 같은 값이면 사번 오름차순으로 정렬하시오.
-- 학습 요소: ORDER BY · NULLS LAST · LIMIT

-- [모범답안]
SELECT employee_id, first_name, commission_pct
FROM employees
ORDER BY commission_pct DESC NULLS LAST, employee_id ASC
LIMIT 10;

-- 해설: DESC 기본은 NULLS FIRST이므로 NULLS LAST를 명시한다.

-- ------------------------------------------------------------------------------
-- [과제문제 11] 페이지 처리: 3페이지 조회
-- ------------------------------------------------------------------------------
-- 문제: 사번 오름차순으로 직원 목록을 페이지당 10명씩 조회할 때 3페이지(21~30번째)의 사번·이름·부서를 조회하시오.
-- 학습 요소: LIMIT · OFFSET

-- [모범답안]
SELECT employee_id, first_name, department_id
FROM employees
ORDER BY employee_id ASC
LIMIT 10 OFFSET 20;

-- 해설: 안정적인 정렬 기준(PK)을 사용하며 OFFSET을 계산한다.

-- ------------------------------------------------------------------------------
-- [과제문제 12] 종합: 부서별 평균 급여 상위 3개
-- ------------------------------------------------------------------------------
-- 문제: 부서가 배정된 재직 직원의 부서별 평균 급여와 인원을 조회하시오. 재직자가 5명 이상이고 평균 급여가 500만 원 이상인 부서만 표시한 뒤 평균 급여 내림차순, 부서 ID 오름차순으로 상위 3개를 출력하시오.
-- 학습 요소: GROUP BY · HAVING · AVG · LIMIT

-- [모범답안]
SELECT department_id, COUNT(*) AS active_count, AVG(salary) AS avg_salary
FROM employees
WHERE employment_status = '재직'
  AND department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 5
   AND AVG(salary) >= 5000000
ORDER BY avg_salary DESC, department_id ASC
LIMIT 3;

-- 해설: 행 필터링, 그룹화, 그룹 조건, 선택 열, 정렬, LIMIT을 모두 사용한다.

