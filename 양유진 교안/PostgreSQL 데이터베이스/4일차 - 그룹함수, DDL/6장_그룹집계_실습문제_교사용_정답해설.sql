-- [실습문제 08] NULL을 제외하는 AVG의 분모 | 교안 7, 31페이지
-- ---------------------------------------------------------------------------
-- 문제: 직원 100, 148, 149, 150번의 수수료율을 대상으로 COUNT(*)/COUNT(commission_pct)/SUM/AVG를
-- 문제: 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 선택직원수,
       COUNT(commission_pct) AS 수수료입력건수,
       SUM(commission_pct) AS 수수료율합계,
       ROUND(AVG(commission_pct), 4) AS 수수료율평균
FROM employees
WHERE employee_id IN (100, 148, 149, 150);
-- 해설: NULL인 직원 100번은 AVG의 분모에서도 제외된다. (0.10+0.03+0.07)/3 ≈ 0.0667.
