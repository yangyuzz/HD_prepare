-- ---------------------------------------------------------------------------
-- [실습문제 20] 부서별 급여 합계 | 교안 15, 20페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서별 월급여 합계를 구하고 합계가 높은 순서로 정렬한다. NULL 부서번호는 제외한다.
