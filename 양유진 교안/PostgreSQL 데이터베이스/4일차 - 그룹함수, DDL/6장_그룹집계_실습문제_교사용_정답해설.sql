-- ---------------------------------------------------------------------------
-- [실습문제 27] WHERE→GROUP BY→HAVING 순서 | 교안 17~18, 21페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직 중이면서 부서가 있는 직원만 고른 후, 부서별 인원이 8명 이상인 부서만 남긴다.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 재직인원
FROM employees
WHERE employment_status = '재직'
  AND department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 8
ORDER BY department_id;
-- 해설: WHERE로 63명만 남긴 다음 그룹화하고, HAVING으로 8명 이상 그룹을 남긴다.
-- 결과 확인: 40:15, 50:10, 60:9

-- ---------------------------------------------------------------------------
-- [실습문제 28] HAVING COUNT 기준 | 교안 20~22페이지
-- ---------------------------------------------------------------------------
-- 문제: 전체 직원 기준으로 인원이 10명 이상인 부서만 조회한다.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 인원
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 10
ORDER BY 인원 DESC;
-- 해설: GROUP BY로 만든 그룹에 대해 COUNT(*) 조건을 적용할 때 HAVING을 쓴다.
-- 결과 확인: 40:16, 50:11

-- ---------------------------------------------------------------------------
-- [실습문제 29] HAVING SUM 기준 | 교안 20~22페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서별 월급여 합계가 5천만 원 이상인 부서를 집계하고 큰 순서로 정렬한다.
-- [모범답안 SQL]
SELECT department_id, SUM(salary) AS 급여합계
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
HAVING SUM(salary) >= 50000000
ORDER BY 급여합계 DESC;
-- 해설: HAVING은 COUNT뿐 아니라 SUM/AVG 등 집계 결과에 조건을 걸 수 있다.
-- 결과 확인: 40:91,900,000 / 50:59,200,000

-- ---------------------------------------------------------------------------
-- [실습문제 30] WHERE에 집계 함수를 쓰면 오류 | 교안 21~22페이지
-- ---------------------------------------------------------------------------
-- 문제: WHERE COUNT(*) 오류를 확인하고 HAVING COUNT(*) >= 5로 수정해 조회한다.
-- [모범답안 SQL]
-- 오류: 집계 이전에 WHERE COUNT(*)를 사용할 수 없다.
-- SELECT department_id, COUNT(*) FROM employees
-- WHERE COUNT(*) >= 5 GROUP BY department_id;
SELECT department_id, COUNT(*) AS 직원수
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 5
ORDER BY department_id;
-- 해설: 논리적으로 WHERE는 GROUP BY 전에 평가되므로 집계 함수 결과를 볼 수 없다. HAVING은 그룹을 만든 뒤 평가된다.

-- ---------------------------------------------------------------------------
-- [실습문제 31] 직무별 평균 급여 HAVING | 교안 20~22페이지
-- ---------------------------------------------------------------------------
-- 문제: 직원 수가 2명 이상인 직무 중 평균 월급여가 500만원 이상인 직무를 구한다.
-- [모범답안 SQL]
SELECT job_id, COUNT(*) AS 인원,
       ROUND(AVG(salary), 0) AS 평균급여
FROM employees
GROUP BY job_id
HAVING COUNT(*) >= 2 AND AVG(salary) >= 5000000
ORDER BY 평균급여 DESC;
-- 해설: HAVING에 여러 집계 조건을 AND로 연결할 수 있다. 평균급여 별칭 대신 HAVING에 AVG(salary)를 직접 써야 한다.


