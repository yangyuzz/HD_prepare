-- ---------------------------------------------------------------------------
-- [실습문제 15] 6명으로 GROUP BY 그룹 형성 | 교안 13~14페이지
-- ---------------------------------------------------------------------------
-- 문제: 사번 101, 102, 104, 113, 123, 124만 조회해 부서 10/20/40의 묶음이 1/2/3명인지 확인한다.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 직원수
FROM employees
WHERE employee_id IN (101, 102, 104, 113, 123, 124)
GROUP BY department_id
ORDER BY department_id;
-- 해설: WHERE로 6명을 선별한 뒤 department_id 기준으로 세 그룹을 만들며, SELECT에서 그룹별 집계값을 반환한다.
-- 결과 확인: 10:1, 20:2, 40:3

-- ---------------------------------------------------------------------------
-- [실습문제 16] 부서별 인원과 NULL 그룹 | 교안 13~15페이지
-- ---------------------------------------------------------------------------
-- 문제: NULL 부서번호를 포함하여 부서번호별 직원 수를 집계한다. 왜 결과가 9그룹인지 설명한다.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 직원수
FROM employees
GROUP BY department_id
ORDER BY department_id NULLS LAST;
-- 해설: NULL인 department_id도 하나의 그룹을 형성한다. 고유한 비NULL 부서 8개+NULL 그룹 1개다.
-- 결과 확인: 8개 유효 부서 그룹 + NULL 그룹(2명)

-- ---------------------------------------------------------------------------
-- [실습문제 17] 직원 수가 많은 부서 상위 3개 | 교안 13~15페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서번호가 있는 직원만 그룹화하고, 직원 수 내림차순으로 상위 3개 부서를 조회한다.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 직원수
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
ORDER BY 직원수 DESC, department_id
LIMIT 3;
-- 해설: WHERE는 개별 직원 행을 먼저 걸러낸다. 그룹화 후 ORDER BY와 LIMIT를 적용한다.
-- 결과 확인: 40:16 / 50:11 / 60:9

-- ---------------------------------------------------------------------------
-- [실습문제 18] 직무별 직원 수 | 교안 15페이지
-- ---------------------------------------------------------------------------
