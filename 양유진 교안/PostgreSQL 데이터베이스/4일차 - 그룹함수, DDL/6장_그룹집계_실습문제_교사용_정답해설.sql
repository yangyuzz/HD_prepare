-- ---------------------------------------------------------------------------
-- [실습문제 01] 집계의 역할: 여러 행을 하나로 | 교안 5~6페이지
-- ---------------------------------------------------------------------------
-- 문제: employees의 전체 직원 수를 한 행으로 집계한다. 조회 전 행 수와 결과 행 수를 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체직원수
FROM employees;
-- 해설: COUNT(*)는 전체 행 개수를 세는 집계 함수다. WHERE/GROUP BY가 없으면 전체를 1행으로 요약한다.
-- 결과 확인: 전체직원수=69, 출력 1행

-- ---------------------------------------------------------------------------
-- [실습문제 02] COUNT 세 가지 형태 | 교안 7~9페이지
-- ---------------------------------------------------------------------------
-- 문제: 전체 직원 수, 부서번호가 NULL이 아닌 직원 수, 고유한 부서번호 개수를 한 행으로 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체직원,
       COUNT(department_id) AS 부서배정,
       COUNT(DISTINCT department_id) AS 부서종류
FROM employees;
-- 해설: COUNT(*)는 NULL을 포함한 모든 행, COUNT(컬럼)은 NULL이 아닌 값, COUNT(DISTINCT 컬럼)은 NULL 제외
-- 해설: 고유값을 센다.
-- 결과 확인: 69 / 67 / 8

-- ---------------------------------------------------------------------------
-- [실습문제 03] COUNT(*)와 COUNT(commission_pct) | 교안 7~8페이지
-- ---------------------------------------------------------------------------
-- 문제: 전체 직원 중 수수료율이 등록된 직원 수를 COUNT 두 방식으로 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체직원,
       COUNT(commission_pct) AS 수수료등록직원,
       COUNT(*) - COUNT(commission_pct) AS 미등록직원
FROM employees;
-- 해설: NULL 값을 포함하는 컬럼에서 COUNT(컬럼)은 값이 없는 행을 세지 않는다.
-- 결과 확인: 69 / 8 / 61

-- ---------------------------------------------------------------------------
-- [실습문제 04] COUNT(DISTINCT) 직무 종류 | 교안 8~9페이지
