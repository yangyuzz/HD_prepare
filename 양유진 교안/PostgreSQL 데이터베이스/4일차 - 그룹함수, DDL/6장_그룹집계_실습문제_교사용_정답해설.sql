-- [모범답안 SQL]
SELECT job_id, COUNT(*) AS 직원수
FROM employees
GROUP BY job_id
ORDER BY 직원수 DESC, job_id;
-- 해설: GROUP BY 기준 컬럼을 department_id에서 job_id로 바꾸면 각 직무별 집계값을 구한다.

