FROM employees
GROUP BY job_id
ORDER BY job_id;
-- 해설: GROUP BY 결과는 한 그룹당 1행이므로 현재 직무가 11종이면 11행이다.
-- 결과 확인: 11개 직무 그룹, 결과 11행


