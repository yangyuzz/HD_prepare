-- ---------------------------------------------------------------------------
-- [실습문제 09] 0/1 값의 SUM과 AVG | 교안 6, 31페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직이면 1, 그렇지 않으면 0인 표현식을 SUM과 AVG에 넣어 건수와 비율을 확인한다.
-- [모범답안 SQL]
SELECT SUM(CASE WHEN employment_status = '재직' THEN 1 ELSE 0 END) AS 재직직원수,
       ROUND(AVG(CASE WHEN employment_status = '재직' THEN 1 ELSE 0 END)::NUMERIC * 100, 2) AS 재직률_pct
FROM employees;
-- 해설: 0/1 값에서 SUM은 참인 행의 수, AVG는 참인 행의 비율이 된다.
-- 결과 확인: 재직 65명 / 94.20%

-- ---------------------------------------------------------------------------
-- [실습문제 10] 대상 행 0개일 때 집계 반환 | 교안 11, 31페이지
-- ---------------------------------------------------------------------------
-- 문제: 존재하지 않는 직무 NO_JOB을 검색해 COUNT/SUM/AVG/MIN/MAX 반환값을 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 직원수,
       SUM(salary) AS 급여합계,
       AVG(salary) AS 평균급여,
       MIN(salary) AS 최저급여,
       MAX(salary) AS 최고급여
FROM employees
WHERE job_id = 'NO_JOB';
-- 해설: 대상 행이 0개일 때 COUNT는 0, SUM·AVG·MIN·MAX는 NULL이다. 결과는 0행이 아니라 집계값 1행으로 나온다.
-- 결과 확인: COUNT=0 / 나머지 모두 NULL

