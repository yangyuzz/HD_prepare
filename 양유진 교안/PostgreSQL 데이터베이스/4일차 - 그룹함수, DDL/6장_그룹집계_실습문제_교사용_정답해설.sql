-- ---------------------------------------------------------------------------
-- [실습문제 13] NULLIF로 0 나누기 방지 | 교안 31~32페이지
-- ---------------------------------------------------------------------------
-- 문제: 값이 0인 분모를 NULL로 바꾸면 나눗셈 오류 대신 NULL 결과를 얻는지 확인한다.
-- [모범답안 SQL]
SELECT NULLIF(0, 0) AS 분모0처리,
       10::NUMERIC / NULLIF(0, 0) AS 안전한계산,
       10::NUMERIC / NULLIF(2, 0) AS 정상계산;
-- 해설: NULLIF(a,b)는 a=b일 때 NULL, 다를 때 a를 반환한다. 0 나누기 오류를 예방한다.
-- 결과 확인: NULL / NULL / 5

-- ---------------------------------------------------------------------------
-- [실습문제 14] 비율 공식: NUMERIC과 NULLIF | 교안 26, 31~32페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직 직원 수 / 전체 직원 수 × 100을 안전하게 계산하고 둘째 자리까지 반올림한다.
-- [모범답안 SQL]
SELECT ROUND(
           COUNT(*) FILTER (WHERE employment_status = '재직')::NUMERIC
           / NULLIF(COUNT(*), 0) * 100, 2
       ) AS 재직률_pct
FROM employees;
-- 해설: 정수 나눗셈을 피하기 위해 분자를 NUMERIC으로 바꾸고, 분모가 0인 경우를 대비해 NULLIF를 사용한다.
-- 결과 확인: 94.20


