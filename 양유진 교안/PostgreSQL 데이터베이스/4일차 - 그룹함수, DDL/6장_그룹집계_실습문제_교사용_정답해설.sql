-- ---------------------------------------------------------------------------
-- [실습문제 42] 프로젝트 상태별 그룹 집계 응용 | 교안 15, 25~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 기존 hd.projects에서 상태별 프로젝트 수와 고예산(5억 원 이상) 프로젝트 수를 집계한다. JOIN은 사용하지 않는다.
-- [모범답안 SQL]
SELECT project_status,
       COUNT(*) AS 프로젝트수,
       COUNT(*) FILTER (WHERE budget >= 500000000) AS 고예산프로젝트수,
       SUM(budget) AS 총예산
FROM projects
GROUP BY project_status
ORDER BY project_status;
