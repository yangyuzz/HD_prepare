-- ---------------------------------------------------------------------------
-- [실습문제 32] CASE WHEN 방식의 조건부 COUNT | 교안 24, 28페이지
-- ---------------------------------------------------------------------------
-- 문제: 하나의 쿼리로 재직/휴직/퇴사 인원을 CASE WHEN과 COUNT로 나란히 집계한다.
-- [모범답안 SQL]
SELECT
  COUNT(CASE WHEN employment_status = '재직' THEN 1 END) AS 재직,
  COUNT(CASE WHEN employment_status = '휴직' THEN 1 END) AS 휴직,
  COUNT(CASE WHEN employment_status = '퇴사' THEN 1 END) AS 퇴사
FROM employees;
-- 해설: CASE WHEN 조건을 만족하지 않으면 NULL이 되므로 COUNT에 포함되지 않는다.
-- 결과 확인: 65 / 2 / 2

-- ---------------------------------------------------------------------------
-- [실습문제 33] FILTER 기본 문법 | 교안 25~26페이지
-- ---------------------------------------------------------------------------
-- 문제: CASE WHEN 대신 FILTER를 이용해 상태별 인원을 구한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE employment_status = '재직') AS 재직,
       COUNT(*) FILTER (WHERE employment_status = '휴직') AS 휴직,
       COUNT(*) FILTER (WHERE employment_status = '퇴사') AS 퇴사
FROM employees;
-- 해설: FILTER (WHERE 조건)은 그 집계 함수의 입력만 제한하므로 전체 COUNT(*)는 69로 유지된다.
-- 결과 확인: 69 / 65 / 2 / 2

-- ---------------------------------------------------------------------------
-- [실습문제 34] FILTER와 일반 WHERE 차이 | 교안 25~27페이지
-- ---------------------------------------------------------------------------
-- 문제: 전체직원/재직자 수를 한 쿼리에서 구한 후, 일반 WHERE를 쓴 쿼리의 COUNT(*)와 결과를 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체인원,
       COUNT(*) FILTER (WHERE employment_status = '재직') AS 재직인원
FROM employees;

SELECT COUNT(*) AS 필터링후행수
FROM employees
WHERE employment_status = '재직';
-- 해설: FILTER는 각 집계 함수만 제한, 일반 WHERE는 쿼리 전체 입력 행을 제한한다.
-- 결과 확인: 첫 쿼리 69/65, 둘째 쿼리 65

-- ---------------------------------------------------------------------------
-- [실습문제 35] 여러 부서 조건부 집계 | 교안 26~27페이지
-- ---------------------------------------------------------------------------
-- 문제: 개발팀(40), 데이터분석팀(50), 영업팀(60)의 전체 인원을 한 행에서 비교한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE department_id = 40) AS 개발,
       COUNT(*) FILTER (WHERE department_id = 50) AS 분석,
       COUNT(*) FILTER (WHERE department_id = 60) AS 영업
FROM employees;
-- 해설: 한 테이블의 행을 반복 조회하지 않고 조건별 집계를 한 SELECT에서 계산한다.
-- 결과 확인: 69 / 16 / 11 / 9

-- ---------------------------------------------------------------------------
-- [실습문제 36] 조건부 합계 | 교안 25~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직 직원 급여 합계와 휴직 직원 급여 합계를 각각 FILTER로 구한다.
-- [모범답안 SQL]
SELECT SUM(salary) FILTER (WHERE employment_status = '재직') AS 재직급여합계,
       SUM(salary) FILTER (WHERE employment_status = '휴직') AS 휴직급여합계,
       SUM(salary) AS 전체급여합계
FROM employees;
-- 해설: FILTER는 COUNT뿐 아니라 SUM/AVG 등 다른 집계 함수에도 적용할 수 있다.

-- ---------------------------------------------------------------------------
-- [실습문제 37] 부서별 재직·휴직·퇴사 | 교안 29페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서별 인원과 상태별 인원을 하나의 행에 출력한다.
-- [모범답안 SQL]
SELECT department_id,
       COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE employment_status = '재직') AS 재직,
       COUNT(*) FILTER (WHERE employment_status = '휴직') AS 휴직,
       COUNT(*) FILTER (WHERE employment_status = '퇴사') AS 퇴사
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
ORDER BY department_id;
-- 해설: GROUP BY는 부서별로 행을 묶고 FILTER는 부서 그룹 안에서 조건별 수를 계산한다.

-- ---------------------------------------------------------------------------
-- [실습문제 38] 부서별 재직률과 분모 보호 | 교안 26, 29, 31~32페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서별 재직 인원 / 전체 인원 * 100을 구한다. 정수 나눗셈 방지와 0분모 처리까지 함께 사용한다.
-- [모범답안 SQL]
SELECT department_id,
       COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE employment_status = '재직') AS 재직,
       ROUND(
         COUNT(*) FILTER (WHERE employment_status = '재직')::NUMERIC
         / NULLIF(COUNT(*), 0) * 100, 1
       ) AS 재직률_pct
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
ORDER BY department_id;
-- 해설: ::NUMERIC은 소수점 결과를 보존하며 NULLIF는 분모가 0인 경우를 보호한다.

-- ---------------------------------------------------------------------------
-- [실습문제 39] CASE WHEN과 FILTER 결과 검증 | 교안 24~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 두 방식으로 재직 인원을 계산해 같은 값이 나오는지 검사한다.
-- [모범답안 SQL]
SELECT COUNT(CASE WHEN employment_status = '재직' THEN 1 END) AS CASE방식,
       COUNT(*) FILTER (WHERE employment_status = '재직') AS FILTER방식,
       COUNT(CASE WHEN employment_status = '재직' THEN 1 END)
       = COUNT(*) FILTER (WHERE employment_status = '재직') AS 결과일치
FROM employees;
-- 해설: 두 방식은 조건부 COUNT를 표현하는 다른 방법이다. 반환 결과가 같음을 확인할 수 있다.
-- 결과 확인: 65 / 65 / true

-- ---------------------------------------------------------------------------
-- [실습문제 40] 집계 별칭: ORDER BY는 가능, HAVING은 불가 | 교안 30~32페이지
-- ---------------------------------------------------------------------------
-- 문제: GROUP BY 집계에 새로운 별칭 cnt를 사용해 ORDER BY를 실행한다. HAVING에서 cnt를 사용하는 오류 쿼리는 주석으로만
-- 문제: 보관한다.
-- [모범답안 SQL]
-- PostgreSQL에서 HAVING cnt >= 5는 인식되지 않는다.
-- SELECT department_id, COUNT(*) AS cnt
-- FROM employees GROUP BY department_id HAVING cnt >= 5;
SELECT department_id, COUNT(*) AS cnt
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 5
ORDER BY cnt DESC, department_id;
-- 해설: ORDER BY는 SELECT 별칭을 사용할 수 있지만 HAVING에는 원래 집계식을 작성해야 한다.

-- ---------------------------------------------------------------------------
-- [실습문제 41] 별칭과 원본 컬럼 이름 충돌 방지 | 교안 30~32페이지
-- ---------------------------------------------------------------------------
