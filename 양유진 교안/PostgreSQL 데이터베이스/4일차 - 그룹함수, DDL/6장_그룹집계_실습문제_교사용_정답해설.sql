-- [모범답안 SQL]
SELECT COUNT(*) AS 직원수,
       COUNT(DISTINCT job_id) AS 직무종류수
FROM employees;
-- 해설: 직무는 직원마다 중복되므로 COUNT(DISTINCT job_id)로 종류를 센다.
-- 결과 확인: 직원수 69 / 직무종류수 11

