-- ---------------------------------------------------------------------------
-- [과제문제 10] 전체 직원 상태/부서 스냅샷 | 교안 24~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 전체 직원 수, 재직/휴직/퇴사 인원, 개발팀·데이터분석팀 인원을 한 번의 SELECT로 조회하시오. FILTER를 사용하시오.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체인원,
       COUNT(*) FILTER (WHERE employment_status='재직') AS 재직,
       COUNT(*) FILTER (WHERE employment_status='휴직') AS 휴직,
       COUNT(*) FILTER (WHERE employment_status='퇴사') AS 퇴사,
       COUNT(*) FILTER (WHERE department_id=40) AS 개발팀,
       COUNT(*) FILTER (WHERE department_id=50) AS 데이터분석팀
FROM employees;
-- 해설: 서로 다른 조건의 집계를 한 행에 출력하는 FILTER의 장점을 보여준다.
-- 결과 확인: 69 / 65 / 2 / 2 / 16 / 11

-- ---------------------------------------------------------------------------
-- [과제문제 11] 직무별 재직률 계산 | 교안 26, 29~32페이지
-- ---------------------------------------------------------------------------
-- 문제: 직무별 전체 인원, 재직 인원과 재직률(%, 소수 2자리)을 구하시오. 0분모 안전 처리를 포함하고 재직률 오름차순으로 정렬하시오.
-- [모범답안 SQL]
SELECT job_id,
       COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE employment_status='재직') AS 재직,
       ROUND(
         COUNT(*) FILTER (WHERE employment_status='재직')::NUMERIC
         / NULLIF(COUNT(*),0) * 100, 2
       ) AS 재직률_pct
FROM employees
GROUP BY job_id
ORDER BY 재직률_pct, job_id;
-- 해설: COUNT(*) FILTER + GROUP BY + ::NUMERIC + NULLIF를 함께 적용한다.

-- ---------------------------------------------------------------------------
-- [과제문제 12] 팀별 부재율 0분모 안전 처리 | 교안 26, 29~32페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서별 휴직·퇴사 인원을 부재자로 정의하고, 부재율(%, 소수 1자리)을 계산하시오. 전체 인원과 부재 인원을 함께 출력하고 부재율이 높은
-- 문제: 순서로 정렬하시오.
-- [모범답안 SQL]
SELECT department_id,
       COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE employment_status IN ('휴직','퇴사')) AS 부재인원,
       ROUND(
         COUNT(*) FILTER (WHERE employment_status IN ('휴직','퇴사'))::NUMERIC
         / NULLIF(COUNT(*),0) * 100, 1
       ) AS 부재율_pct
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
ORDER BY 부재율_pct DESC, department_id;
-- 해설: 휴직+퇴사를 부재로 정의했다는 점을 주석에 설명하고 FILTER 조건에 IN을 적용한다.

-- ---------------------------------------------------------------------------
-- [과제문제 13] CASE WHEN와 FILTER 동일성 검증 | 교안 24~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직 직원 수를 CASE WHEN 및 FILTER로 각각 계산하고 두 값이 일치하는지 비교하는 결과 컬럼도 출력하시오.
-- [모범답안 SQL]
SELECT COUNT(CASE WHEN employment_status='재직' THEN 1 END) AS CASE집계,
       COUNT(*) FILTER (WHERE employment_status='재직') AS FILTER집계,
       COUNT(CASE WHEN employment_status='재직' THEN 1 END)
         = COUNT(*) FILTER (WHERE employment_status='재직') AS 일치여부
FROM employees;
-- 해설: 같은 업무 질문에 대해 조건부 COUNT의 두 가지 표현법을 사용할 수 있다.

-- ---------------------------------------------------------------------------
-- [과제문제 14] 프로젝트 예산 보고서: 그룹·집계·FILTER | 교안 15, 20, 25~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 기존 projects에서 프로젝트 상태별 개수, 예산 합계, 평균 예산, 3억 이상 프로젝트 개수를 구하시오. 프로젝트 수가 2개 이상인
-- 문제: 상태만 출력하시오.
-- [모범답안 SQL]
SELECT project_status,
       COUNT(*) AS 프로젝트수,
       SUM(budget) AS 예산합계,
       ROUND(AVG(budget), 0) AS 평균예산,
       COUNT(*) FILTER (WHERE budget >= 300000000) AS 고예산프로젝트
FROM projects
GROUP BY project_status
HAVING COUNT(*) >= 2
ORDER BY 프로젝트수 DESC, project_status;
-- 해설: GROUP BY·HAVING·FILTER·SUM·AVG를 프로젝트라는 독립 테이블에 통합 적용한다.

