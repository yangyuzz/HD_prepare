-- ---------------------------------------------------------------------------
-- [과제문제 04] 부서별 급여 현황 TOP 5 | 교안 13~16페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서번호별 직원 수, 급여합계, 평균급여(반올림한 정수)를 계산하고 급여합계 상위 5개만 조회하시오. NULL 부서는 제외한다.
-- [모범답안 SQL]
SELECT department_id,
       COUNT(*) AS 직원수,
       SUM(salary) AS 급여합계,
       ROUND(AVG(salary), 0) AS 평균급여
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
ORDER BY 급여합계 DESC, department_id
LIMIT 5;
-- 해설: GROUP BY와 세 집계 함수를 결합하고 집계 결과 별칭으로 정렬한다.

-- ---------------------------------------------------------------------------
-- [과제문제 05] 직무별 평균 급여와 직원 수 | 교안 15~16페이지
-- ---------------------------------------------------------------------------
-- 문제: 직무별 직원 수·평균급여(만원 단위 소수 1자리)·최저급여를 조회하시오. 직원 수 내림차순, 직무코드 오름차순으로 정렬하시오.
-- [모범답안 SQL]
SELECT job_id,
       COUNT(*) AS 직원수,
       ROUND(AVG(salary)::NUMERIC / 10000, 1) AS 평균급여_만원,
       MIN(salary) AS 최저급여
FROM employees
GROUP BY job_id
ORDER BY 직원수 DESC, job_id;
-- 해설: AVG와 ROUND를 활용해 임의 단위로 값을 표현할 수 있다.

-- ---------------------------------------------------------------------------
-- [과제문제 06] 부서별 재직/휴직/퇴사 분포 | 교안 15, 26~29페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서별 전체 인원, 재직 인원, 휴직 인원, 퇴사 인원을 한 행으로 조회하시오. NULL 부서는 제외한다.
-- [모범답안 SQL]
SELECT department_id,
       COUNT(*) AS 전체,
       COUNT(*) FILTER (WHERE employment_status='재직') AS 재직,
       COUNT(*) FILTER (WHERE employment_status='휴직') AS 휴직,
       COUNT(*) FILTER (WHERE employment_status='퇴사') AS 퇴사
FROM employees
WHERE department_id IS NOT NULL
GROUP BY department_id
ORDER BY department_id;
-- 해설: GROUP BY와 FILTER를 결합한다.


-- ================================================================================
-- 03 HAVING
-- ================================================================================

-- ---------------------------------------------------------------------------
-- [과제문제 07] 재직 인원 5명 이상인 부서 | 교안 17~22페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직 직원만 대상으로 부서별 인원을 집계하고, 재직 인원이 5명 이상인 부서만 조회하시오. 큰 순서로 정렬하시오.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 재직인원
FROM employees
WHERE employment_status='재직'
  AND department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 5
ORDER BY 재직인원 DESC, department_id;
-- 해설: WHERE에서 재직직원만 선별한 뒤 그룹을 집계하고 HAVING으로 최소 인원을 적용한다.

-- ---------------------------------------------------------------------------
-- [과제문제 08] 직무별 급여 규모가 큰 그룹 | 교안 15, 20~22페이지
-- ---------------------------------------------------------------------------
-- 문제: 직무별 월급여 총액이 3천만 원 이상이고 해당 직무 직원이 3명 이상인 그룹만 출력하시오. 급여 총액 순으로 정렬하시오.
-- [모범답안 SQL]
SELECT job_id,
       COUNT(*) AS 인원,
       SUM(salary) AS 급여합계
FROM employees
GROUP BY job_id
HAVING SUM(salary) >= 30000000
   AND COUNT(*) >= 3
ORDER BY 급여합계 DESC;
-- 해설: HAVING에서 SUM과 COUNT 조건을 결합한다.

-- ---------------------------------------------------------------------------
-- [과제문제 09] 평균 급여가 높은 직무군 분석 | 교안 15, 20~22페이지
-- ---------------------------------------------------------------------------
-- 문제: 재직 직원만 대상으로 직무별 인원과 평균 급여를 계산하고, 재직 직원 3명 이상·평균 급여 500만원 이상인 직무만 조회하시오.
-- [모범답안 SQL]
SELECT job_id,
       COUNT(*) AS 재직직원수,
       ROUND(AVG(salary), 0) AS 평균급여
FROM employees
WHERE employment_status='재직'
GROUP BY job_id
HAVING COUNT(*) >= 3
   AND AVG(salary) >= 5000000
ORDER BY 평균급여 DESC;
-- 해설: 행 조건은 WHERE, 그룹 집계 결과 조건은 HAVING이다.


