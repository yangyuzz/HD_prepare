-- ---------------------------------------------------------------------------
-- [과제문제 01] 전체 직원 급여 보고서 | 교안 5~10페이지
-- ---------------------------------------------------------------------------
-- 문제: 직원 수, 총급여, 평균급여(소수 2자리), 최저/최고 급여, 최초/최근 입사일을 한 행으로 보고하시오.
-- [모범답안 SQL]
SELECT COUNT(*) AS 직원수,
       SUM(salary) AS 총급여,
       ROUND(AVG(salary), 2) AS 평균급여,
       MIN(salary) AS 최저급여,
       MAX(salary) AS 최고급여,
       MIN(hire_date) AS 최초입사일,
       MAX(hire_date) AS 최근입사일
FROM employees;
-- 해설: 전체 행을 집계하는 COUNT·SUM·AVG·MIN·MAX를 한 쿼리로 활용한다.

-- ---------------------------------------------------------------------------
-- [과제문제 02] 수수료율 NULL의 영향 비교 | 교안 7~10페이지
-- ---------------------------------------------------------------------------
-- 문제: 전체 직원의 commission_pct 대해 직원 수, 등록 인원, 등록된 직원의 평균 수수료율, NULL을 0으로 간주한 전체 평균을
-- 문제: 출력하시오.
-- [모범답안 SQL]
SELECT COUNT(*) AS 전체직원,
       COUNT(commission_pct) AS 등록직원,
       ROUND(AVG(commission_pct), 4) AS 등록직원평균,
       ROUND(AVG(COALESCE(commission_pct, 0)), 4) AS 전체직원평균_미등록0
FROM employees;
-- 해설: AVG(commission_pct)는 NULL을 분모에서 제외한다. COALESCE를 쓰면 NULL을 0으로 바꾼 뒤 69명 평균을 계산한다.

-- ---------------------------------------------------------------------------
-- [과제문제 03] 미등록 데이터가 없는지 확인 | 교안 7~9페이지
-- ---------------------------------------------------------------------------
-- 문제: 부서 미배정 직원 수와 부서 배정 직원 수, 고유 부서번호 개수를 한 행으로 출력하시오.
-- [모범답안 SQL]
SELECT COUNT(*) - COUNT(department_id) AS 부서미배정,
       COUNT(department_id) AS 부서배정,
       COUNT(DISTINCT department_id) AS 부서종류
FROM employees;
-- 해설: COUNT(*)와 COUNT(컬럼)의 차이로 NULL 행 개수를 계산한다.
-- 결과 확인: 2 / 67 / 8


