-- 문제: SQL형: job_id별 직원 수를 집계하고 인원이 많은 순서로 정렬한다.
-- [모범답안 SQL]
SELECT job_id, COUNT(*) AS 직원수
FROM employees
GROUP BY job_id
ORDER BY 직원수 DESC, job_id;
