-- ---------------------------------------------------------------------------
-- [복습문제 01] COUNT 반환 차이 설명 | 교안 7~9, 31페이지
-- ---------------------------------------------------------------------------
-- 문제: 개념형: COUNT(*), COUNT(department_id), COUNT(DISTINCT department_id)가 각각 무엇을 세는지
-- 문제: 설명하고 실제 값도 작성한다.
-- [개념형 모범답안 - 주석]
-- 해설: COUNT(*)는 69행, COUNT(department_id)는 NULL 제외 67행, COUNT(DISTINCT department_id)는
-- 해설: 고유 부서 8개다.
-- 결과 확인: 69 / 67 / 8

-- ---------------------------------------------------------------------------
-- [복습문제 02] 집계 종류 구분 | 교안 7, 10페이지
-- ---------------------------------------------------------------------------
-- 문제: 개념형: SUM·AVG·MIN·MAX의 역할을 한 문장씩 쓰고 AVG가 NULL 값을 어떻게 처리하는지 설명한다.
-- [개념형 모범답안 - 주석]
-- 해설: SUM=합계, AVG=평균(비NULL 값만), MIN=최솟값, MAX=최댓값. 숫자 외에도 날짜·문자 MIN/MAX가 가능하다.

-- ---------------------------------------------------------------------------
-- [복습문제 03] 급여 평균과 최소·최대 | 교안 10페이지
-- ---------------------------------------------------------------------------
-- 문제: SQL형: employees에서 직원 수, 평균 급여(둘째 자리), 최저·최고 급여를 조회한다.
-- [모범답안 SQL]
SELECT COUNT(*) AS 직원수,
       ROUND(AVG(salary), 2) AS 평균급여,
       MIN(salary) AS 최저급여,
       MAX(salary) AS 최고급여
FROM employees;
-- 해설: GROUP BY가 없으므로 전체 직원이 하나의 집계 행으로 요약된다.

-- ---------------------------------------------------------------------------
-- [복습문제 04] 0행과 NULL 처리 설명 | 교안 11, 31페이지
-- ---------------------------------------------------------------------------
-- 문제: 개념형: 조건에 맞는 행이 0개일 때 COUNT/SUM/AVG/MIN/MAX 결과를 쓰고, SUM을 0으로 표시하는 방법을 설명한다.
-- [개념형 모범답안 - 주석]
-- 해설: COUNT는 0, SUM/AVG/MIN/MAX는 NULL. COALESCE(SUM(salary),0)으로 0 표시.

-- ---------------------------------------------------------------------------
-- [복습문제 05] 안전한 비율 만들기 | 교안 6, 26, 31~32페이지
-- ---------------------------------------------------------------------------
-- 문제: SQL형: 전체 직원 중 재직 직원 비율을 ROUND(...,2)로 구한다. ::NUMERIC과 NULLIF를 반드시 사용한다.
-- [모범답안 SQL]
SELECT ROUND(
         COUNT(*) FILTER (WHERE employment_status = '재직')::NUMERIC
         / NULLIF(COUNT(*), 0) * 100, 2
       ) AS 재직률_pct
FROM employees;
-- 해설: 분자 NUMERIC 변환으로 정수 나눗셈을 피하고 NULLIF로 0분모를 보호한다.
-- 결과 확인: 94.20

-- ---------------------------------------------------------------------------
-- [복습문제 06] ROUND 타입 오류 설명 | 교안 10, 31페이지
-- ---------------------------------------------------------------------------
-- 문제: 개념형: ROUND(AVG(salary::DOUBLE PRECISION), 2)가 PostgreSQL에서 왜 오류인지, 어떤 형변환으로
-- 문제: 해결하는지 설명한다.
-- [개념형 모범답안 - 주석]
-- 해설: ROUND(double precision, integer) 오버로드가 없어서 오류. ROUND(AVG(salary::DOUBLE
-- 해설: PRECISION)::NUMERIC, 2)로 변환한다.


