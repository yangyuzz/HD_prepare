-- ---------------------------------------------------------------------------
-- [복습문제 13] 부서별 직원 현황표 | 교안 26~29페이지
-- ---------------------------------------------------------------------------
-- 문제: SQL형: 부서번호별 전체·재직·휴직 직원을 집계한다. 부서번호 NULL은 제외한다.
