-- [개념형 모범답안 - 주석]
-- 해설: 작성: SELECT→FROM→WHERE→GROUP BY→HAVING→ORDER BY→LIMIT. 논리: FROM→WHERE→GROUP
-- 해설: BY→HAVING→SELECT→ORDER BY→LIMIT. DISTINCT가 있다면 SELECT 이후, ORDER BY 이전.


