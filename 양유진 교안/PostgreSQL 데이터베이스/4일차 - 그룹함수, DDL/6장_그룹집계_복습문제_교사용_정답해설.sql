-- 03 HAVING
-- ================================================================================

-- ---------------------------------------------------------------------------
-- [복습문제 09] WHERE와 HAVING 비교 | 교안 17~22페이지
-- ---------------------------------------------------------------------------
-- 문제: SQL형: 재직 직원만 집계한 후 재직 인원이 8명 이상인 부서번호와 인원을 조회한다. 부서번호 NULL은 제외한다.
-- [모범답안 SQL]
SELECT department_id, COUNT(*) AS 재직인원
FROM employees
WHERE employment_status = '재직'
  AND department_id IS NOT NULL
GROUP BY department_id
HAVING COUNT(*) >= 8
ORDER BY department_id;
-- 해설: WHERE는 그룹 이전의 개별 행, HAVING은 그룹 이후의 집계 결과를 필터링한다.
-- 결과 확인: 40:15 / 50:10 / 60:9

-- ---------------------------------------------------------------------------
-- [복습문제 10] SQL 논리적 처리 순서 | 교안 17~22페이지
-- ---------------------------------------------------------------------------
